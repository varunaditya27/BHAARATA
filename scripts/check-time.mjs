import assert from 'node:assert/strict';
import { formatDateRange, yearInRange } from '../lib/domain/time.ts';
import { getHistoricalState } from '../lib/geo/historical-state.ts';
const unknown = { startYear:0, endYear:null, startQualifier:'unknown', endQualifier:'unknown', confidence:'unknown' };
assert.equal(formatDateRange(unknown), 'date unknown');
assert.equal(yearInRange(1050,unknown), false);
const data = {polities:[{id:'x',period:unknown}],boundaries:[],events:[],routes:[]};
assert.equal(getHistoricalState(1050,data).activePolities.length,0);
data.boundaries.push({polityId:'x',validFrom:1000,validTo:1100});
assert.equal(getHistoricalState(1050,data).activePolities.length,1);
assert.equal(getHistoricalState(1150,data).activePolities.length,0);
console.log('Unknown dates remain unknown; dated borders can still establish presence.');
